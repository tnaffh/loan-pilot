/**
 * Generate the SQL that re-dates already-imported register rows.
 *
 *   node apps/api/prisma/import-data/gen-date-repair.mjs <old-fixture-dir> <new-fixture-dir>
 *
 * The first import of the register (June 2026) carried two dating defects:
 *   - repayments with no date in the sheet fell back to the tenant's `joinedAt`
 *     (the import instant on production), because the importer handed its own
 *     `YYYY-MM#row` key to a parser expecting "May 2025";
 *   - dates the lender typed as dd/mm had been stored by the sheet as mm/dd, so
 *     "06/10/23" (6 October) was imported as 10 June.
 *
 * Production cannot simply be re-imported — the lender has been working in
 * LoanPilot since go-live and the importer replaces every loan and payment — so
 * the corrected dates are applied in place. For every imported loan and payment,
 * this compares what the *old* fixtures produced (what is in the database) with
 * what the *corrected* fixtures produce (what a fresh import would write) and
 * emits one guarded UPDATE per changed row. Each guard requires the column to
 * still hold the old imported value, so a date the lender has since corrected by
 * hand is left alone, and re-running the statements is harmless.
 *
 * The derivations below mirror import-raccoons.ts exactly; keep them in step.
 * Run with TZ=UTC so month arithmetic matches a UTC import.
 */
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const [oldDir, newDir] = process.argv.slice(2);
if (!oldDir || !newDir) {
  console.error('usage: gen-date-repair.mjs <old-fixture-dir> <new-fixture-dir>');
  process.exit(1);
}

const load = (dir, name) => JSON.parse(readFileSync(join(dir, name), 'utf8'));

const MONTHS = {
  jan: 0,
  feb: 1,
  mar: 2,
  apr: 3,
  may: 4,
  jun: 5,
  jul: 6,
  aug: 7,
  sep: 8,
  oct: 9,
  nov: 10,
  dec: 11,
};
const toDate = (iso) => (iso ? new Date(`${iso}T00:00:00.000Z`) : null);
const monthLabelToDate = (label) => {
  const m = (label ?? '').trim().match(/([A-Za-z]+)\s+(\d{4})/);
  const mon = m ? MONTHS[m[1].slice(0, 3).toLowerCase()] : undefined;
  return mon !== undefined && m ? new Date(Date.UTC(Number(m[2]), mon, 1)) : null;
};
/** Same as @loan-pilot/domain addMonths under TZ=UTC. */
const addMonths = (date, months) => {
  const next = new Date(date);
  next.setUTCMonth(next.getUTCMonth() + months);
  return next;
};
const undatedPaymentDate = (loanKey, nextDueAt) => {
  const m = loanKey.match(/^(\d{4})-(\d{2})#/);
  if (!m) return null;
  const start = new Date(Date.UTC(Number(m[1]), Number(m[2]) - 1, 1));
  const end = new Date(Date.UTC(Number(m[1]), Number(m[2]), 1));
  if (nextDueAt && nextDueAt >= start && nextDueAt < end) return nextDueAt;
  return new Date(end.getTime() - 86_400_000);
};

/** The dates import-raccoons.ts writes for a loan row. */
const loanDates = (row) => {
  const disbursedAt = toDate(row.startDate) ?? monthLabelToDate(row.originMonth);
  const nextDueAt =
    toDate(row.dueDate) ?? (disbursedAt ? addMonths(disbursedAt, row.termMonths || 1) : null);
  return { disbursedAt, nextDueAt };
};

const ts = (date) => `'${date.toISOString().slice(0, 19).replace('T', ' ')}'::timestamp`;
const lit = (text) => `'${String(text).replace(/'/g, "''")}'`;
const same = (a, b) =>
  (a === null && b === null) || (a !== null && b !== null && a.getTime() === b.getTime());

const oldLoans = new Map(load(oldDir, 'raccoons-loans.json').map((row) => [row.loanKey, row]));
const newLoans = load(newDir, 'raccoons-loans.json');
const oldPayments = new Map(
  load(oldDir, 'raccoons-payments.json').map((row) => [`${row.loanKey}~${row.payRef}`, row]),
);
const newPayments = load(newDir, 'raccoons-payments.json');

const out = [];
out.push('-- Re-date register rows imported with the wrong day/month or the join-date fallback.');
out.push('-- Generated by prisma/import-data/gen-date-repair.mjs; every statement is guarded by');
out.push('-- the value the original import wrote, so hand-corrected rows are untouched.');
out.push('');

const newNextDue = new Map();
const counts = { loans: 0, datedPayments: 0, undatedPayments: 0 };

out.push('-- Loans: disbursement (and the payout stamp that mirrors it) and the due date.');
for (const row of newLoans) {
  const after = loanDates(row);
  newNextDue.set(row.loanKey, after.nextDueAt);
  const before = oldLoans.get(row.loanKey);
  if (!before) continue;
  const prior = loanDates(before);
  const sets = [];
  if (!same(prior.disbursedAt, after.disbursedAt) && prior.disbursedAt && after.disbursedAt) {
    sets.push(
      `"disbursedAt" = CASE WHEN "disbursedAt" = ${ts(prior.disbursedAt)} THEN ${ts(after.disbursedAt)} ELSE "disbursedAt" END`,
      `"fundsReleasedAt" = CASE WHEN "fundsReleasedAt" = ${ts(prior.disbursedAt)} THEN ${ts(after.disbursedAt)} ELSE "fundsReleasedAt" END`,
    );
  }
  if (!same(prior.nextDueAt, after.nextDueAt) && prior.nextDueAt && after.nextDueAt) {
    sets.push(
      `"nextDueAt" = CASE WHEN "nextDueAt" = ${ts(prior.nextDueAt)} THEN ${ts(after.nextDueAt)} ELSE "nextDueAt" END`,
    );
  }
  if (sets.length === 0) continue;
  counts.loans += 1;
  out.push(`UPDATE "Loan" SET ${sets.join(', ')} WHERE "externalRef" = ${lit(row.loanKey)};`);
}

out.push('');
out.push('-- Repayments that carried a (mis-read) date.');
for (const row of newPayments) {
  const ref = `${row.loanKey}~${row.payRef}`;
  const before = oldPayments.get(ref);
  if (!before || !before.paidAt || !row.paidAt || before.paidAt === row.paidAt) continue;
  counts.datedPayments += 1;
  out.push(
    `UPDATE "Payment" SET "paidAt" = ${ts(toDate(row.paidAt))} WHERE "externalRef" = ${lit(ref)} AND "paidAt" = ${ts(toDate(before.paidAt))};`,
  );
}

out.push('');
out.push('-- Repayments with no date in the sheet: they sat on the tenant join date, and belong');
out.push("-- in their loan's register month (its due date when inside the month, else month end).");
for (const row of newPayments) {
  if (row.paidAt) continue;
  const ref = `${row.loanKey}~${row.payRef}`;
  if (!oldPayments.has(ref)) continue;
  const target = undatedPaymentDate(row.loanKey, newNextDue.get(row.loanKey) ?? null);
  if (!target) continue;
  counts.undatedPayments += 1;
  out.push(
    `UPDATE "Payment" p SET "paidAt" = ${ts(target)} FROM "Tenant" t WHERE p."tenantId" = t.id AND p."externalRef" = ${lit(ref)} AND p."paidAt" = t."joinedAt";`,
  );
}

process.stdout.write(`${out.join('\n')}\n`);
console.error(
  `loans: ${counts.loans}, dated payments: ${counts.datedPayments}, undated payments: ${counts.undatedPayments}`,
);
